def notify_webhook(
    payload: dict,
    url: str | None = None,
    dry_run: bool = False,
    timeout: float = 5.0,
) -> dict:
    """POST payload as JSON to the webhook URL.

    URL resolved from arg or HERMES_WEBHOOK_URL env var.  Returns
    {"notified": bool, "url": str|None, "dry_run": bool, ...}.
    Failures are swallowed (agent must not crash on webhook outage).
    """
    webhook_url = url or os.environ.get("HERMES_WEBHOOK_URL", "").strip()
    if not webhook_url:
        return {"notified": False, "url": None, "reason": "no webhook URL configured"}
    if dry_run:
        return {"notified": False, "url": webhook_url, "dry_run": True, "payload": payload}
    try:
        import urllib.request

        data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        req = urllib.request.Request(
            webhook_url,
            data=data,
            headers={"Content-Type": "application/json", "User-Agent": "hermes-architect/2.0"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8", errors="replace")[:2000]
            return {"notified": True, "url": webhook_url, "status": resp.status, "body": body}
    except Exception as exc:
        return {"notified": False, "url": webhook_url, "error": str(exc)}



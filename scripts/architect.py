"""scripts/architect.py — Architect v2 autonomous agent hooks.

Scope (Issue #4 / Step 6 + Step 11 audit + feedback loop):
- HERMES_AGENT_ENABLED kill switch (env gate, default OFF)
- dry-run (no side-effects)
- File generation (not string patch) — all changes via generate_file()
- EXPLAIN pre-flight before executing migrations / SQL
- gh PR creation via subprocess
- Webhook notification (HERMES_WEBHOOK_URL)
- hits.jsonl logger + pin-memory weighted boost (pin_weight, ttl)
- Audit compatibility with sql/migrations V3 (agent_decision_audit, schema_change_audit)

Pin-memory weighted boost (Librarian C10 tuning):
    boosted = base_score * (1 + pin_weight * ttl_decay)
    ttl_decay = exp(-age_seconds / ttl_seconds)  if ttl > 0 else 1.0
    age = now - pinned_at
"""

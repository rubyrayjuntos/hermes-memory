DEFAULT_HITS_PATH = Path("data/hits.jsonl")

def log_hit(
    entry: dict,
    hits_file: Path | str = DEFAULT_HITS_PATH,
    pin_weight: float | None = None,
    ttl: float | None = None,
    dry_run: bool = False,
) -> dict:
    """Append a single hit record to hits.jsonl (JSON Lines).

    entry: arbitrary dict; will be enriched with _ts, pin_weight, ttl if supplied.
    Returns the enriched record.  In dry-run nothing is written.
    """
    p = Path(hits_file)
    record = dict(entry)
    record.setdefault("_ts", datetime.datetime.now(datetime.timezone.utc).isoformat())
    if pin_weight is not None:
        record["pin_weight"] = float(pin_weight)
    if ttl is not None:
        record["ttl"] = float(ttl)
    # compute boosted_score if score present
    if "score" in record and "pin_weight" in record:
        try:
            age = float(record.get("age_seconds", 0.0))
            ttl_v = float(record.get("ttl", 3600.0))
            pw = float(record["pin_weight"])
            record["boosted_score"] = compute_pin_boost(float(record["score"]), pw, ttl_v, age)
        except Exception:
            pass
    if dry_run:
        record["_dry_run"] = True
        return record
    p.parent.mkdir(parents=True, exist_ok=True)
    line = json.dumps(record, ensure_ascii=False)
    with p.open("a", encoding="utf-8") as fh:
        fh.write(line + "\n")
    return record


def read_hits(
    hits_file: Path | str = DEFAULT_HITS_PATH,
    limit: int = 100,
) -> List[dict]:
    """Read last `limit` hits from hits.jsonl."""
    p = Path(hits_file)
    if not p.exists():
        return []
    lines = p.read_text(encoding="utf-8").strip().splitlines()
    out: List[dict] = []
    for line in lines[-limit:]:
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out



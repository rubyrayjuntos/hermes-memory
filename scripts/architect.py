def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Architect v2 — autonomous agent hooks (kill switch gated)")
    ap.add_argument("--dry-run", action="store_true", help="Print actions without side-effects")
    ap.add_argument("--force", action="store_true", help="Bypass HERMES_AGENT_ENABLED gate (local testing)")
    ap.add_argument("--branch", default=None, help="Branch to push / create PR from")
    ap.add_argument("--title", default=None, help="PR title")
    ap.add_argument("--body", default="", help="PR body")
    ap.add_argument("--base", default="main", help="PR base branch (default: main)")
    ap.add_argument("--dsn", default=None, help="Postgres DSN (for EXPLAIN pre-flight)")
    ap.add_argument("--check-enabled", action="store_true", help="Print kill-switch status and exit")
    ap.add_argument("--migrations-dir", default=None, help="Path to sql/migrations (for file generation)")
    ap.add_argument("--generate-migration", nargs=3, metavar=("VERSION", "DESCRIPTION", "SQL_FILE"),
                    help="Generate a migration file: VERSION DESCRIPTION SQL_FILE (reads SQL_FILE)")
    ap.add_argument("--hits-file", default=str(DEFAULT_HITS_PATH), help="hits.jsonl path")
    ap.add_argument("--pin-weight", type=float, default=None, help="Pin boost weight (for hits logger)")
    ap.add_argument("--ttl", type=float, default=None, help="Pin TTL seconds (for hits logger)")
    args = ap.parse_args(argv)

    if args.check_enabled:
        enabled = is_agent_enabled()
        print(f"HERMES_AGENT_ENABLED={'true' if enabled else 'false'}")
        return 0

    if not require_enabled(force=args.force):
        print("architect: HERMES_AGENT_ENABLED != true — kill switch active, exiting (no-op).", file=sys.stderr)
        return 0

    if args.generate_migration:
        version, description, sql_file = args.generate_migration
        migrations_dir = Path(args.migrations_dir) if args.migrations_dir else Path("sql/migrations")
        sql_body = Path(sql_file).read_text(encoding="utf-8") if Path(sql_file).exists() else sql_file
        # optional EXPLAIN pre-flight if DSN provided
        if args.dsn:
            try:
                import psycopg
                with psycopg.connect(args.dsn, autocommit=True) as conn:
                    results = explain_preflight_for_migration(conn, sql_body)
                    for r in results:
                        if r.get("warnings"):
                            print(f"EXPLAIN warning for {r.get('statement','')!r}: {r['warnings']}", file=sys.stderr)
            except Exception as exc:
                print(f"EXPLAIN pre-flight skipped: {exc}", file=sys.stderr)
        res = generate_migration_file(migrations_dir, version, description, sql_body, dry_run=args.dry_run)
        print(f"{'would generate' if args.dry_run else 'generated'}: {res['path']}  sha256:{res['checksum'][:12]}")
        return 0

    # Generic high-level run (push/PR/webhook)
    return run_architect(
        dry_run=args.dry_run,
        branch=args.branch,
        title=args.title,
        body=args.body,
        base=args.base,
        force=args.force,
        dsn=args.dsn,
    )


if __name__ == "__main__":
    sys.exit(main())

# File generation (not string patch)
# ---------------------------------------------------------------------------

def generate_file(path: Path, content: str, dry_run: bool = False) -> dict:
    """Generate a file atomically; no in-place string patches.

    Returns dict with {path, written, dry_run, checksum, size}.
    In dry-run mode nothing is written and `written` is False.
    """
    p = Path(path)
    checksum = hashlib.sha256(content.encode("utf-8")).hexdigest()
    info = {
        "path": str(p),
        "written": False,
        "dry_run": dry_run,
        "checksum": checksum,
        "size": len(content.encode("utf-8")),
    }
    if dry_run:
        return info
    p.parent.mkdir(parents=True, exist_ok=True)
    # atomic write via temp + rename
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    tmp.replace(p)
    info["written"] = True
    return info


def generate_migration_file(
    migrations_dir: Path,
    version: str,
    description: str,
    sql_body: str,
    dry_run: bool = False,
) -> dict:
    """Generate a new sql/migrations/V{n}__{description}.sql file.

    version: e.g. "V4" or "V4__add_feature" (normalized to V4__snake_case).
    No string patching — the file is rendered from a template.
    """
    migrations_dir = Path(migrations_dir)
    # normalize version
    m = re.match(r"^(V\d+)(?:__(.*))?$", version)
    if not m:
        raise ValueError(f"invalid migration version: {version!r} (expected V{{n}} or V{{n}}__desc)")
    ver = m.group(1)
    desc = m.group(2) or re.sub(r"[^a-z0-9]+", "_", description.lower()).strip("_")
    desc = re.sub(r"[^a-z0-9_]+", "_", desc.lower()).strip("_") or "migration"
    filename = f"{ver}__{desc}.sql"
    header = (
        f"-- {filename} — auto-generated by scripts/architect.py\n"
        f"-- Idempotent via IF NOT EXISTS where applicable.\n\n"
        f"SET search_path = public;\n\n"
    )
    content = header + sql_body.strip() + "\n"
    return generate_file(migrations_dir / filename, content, dry_run=dry_run)


def generate_code_artifact(
    path: Path,
    template: str,
    context: dict,
    dry_run: bool = False,
) -> dict:
    """Render a code artifact from a template string + context.

    Uses Python str.format() for simplicity — no external deps.  All
    placeholders are {key}; missing keys raise KeyError.
    """
    try:
        rendered = template.format(**context)
    except KeyError as exc:
        raise KeyError(f"missing template key: {exc}") from exc
    return generate_file(path, rendered, dry_run=dry_run)


# ---------------------------------------------------------------------------
# EXPLAIN pre-flight
# ---------------------------------------------------------------------------

EXPLAIN_DANGEROUS_PATTERNS = [
    re.compile(r"Seq Scan", re.IGNORECASE),
]

def explain_preflight(
    conn,
    sql: str,
    params: tuple | None = None,
    warn_on_seq_scan: bool = True,
) -> dict:
    """Run EXPLAIN on a SQL statement and return the plan.

    Returns {"ok": bool, "plan": str, "warnings": [str]}.  Does not execute
    the statement itself.  Caller decides whether warnings should block.
    The connection is expected to be a psycopg (sync) connection; falls back
    gracefully when no DB is available.
    """
    cleaned = sql.strip().rstrip(";")
    if not cleaned:
        return {"ok": True, "plan": "", "warnings": []}
    # EXPLAIN only the first statement; skip DDL that EXPLAIN can't handle well
    # We still attempt it — failure is reported as a warning, not a hard error,
    # so offline/dry-run usage doesn't crash.
    explain_sql = f"EXPLAIN {cleaned}"
    plan_text = ""
    warnings: List[str] = []
    try:
        with conn.cursor() as cur:
            if params is not None:
                cur.execute(explain_sql, params)
            else:
                cur.execute(explain_sql)
            rows = cur.fetchall()
            plan_text = "\n".join(r[0] if isinstance(r, (list, tuple)) else str(r) for r in rows)
    except Exception as exc:
        warnings.append(f"EXPLAIN failed: {exc}")
        return {"ok": False, "plan": plan_text, "warnings": warnings}

    if warn_on_seq_scan:
        for pat in EXPLAIN_DANGEROUS_PATTERNS:
            if pat.search(plan_text):
                # Heuristic: Seq Scan on a table > 0 rows deserves a warning.
                # We don't fail — we warn so the caller can decide.
                warnings.append(f"EXPLAIN warning: {pat.pattern!r} detected — consider adding an index")
                break
    return {"ok": True, "plan": plan_text, "warnings": warnings}


def explain_preflight_for_migration(
    conn,
    migration_sql: str,
) -> List[dict]:
    """Split a migration file into statements and EXPLAIN each SELECT/INSERT/UPDATE/DELETE.

    DDL statements are skipped for EXPLAIN but reported as {"skipped": True}.
    Returns a list of per-statement results.
    """
    # naive split on ; — good enough for pre-flight; not a SQL parser
    statements = [s.strip() for s in migration_sql.split(";") if s.strip()]
    results: List[dict] = []
    for stmt in statements:
        upper = stmt.lstrip().upper()
        if upper.startswith(("SELECT", "INSERT", "UPDATE", "DELETE", "WITH")):
            res = explain_preflight(conn, stmt + ";")
            res["statement"] = stmt[:120]
            results.append(res)
        else:
            results.append({"ok": True, "skipped": True, "statement": stmt[:120], "plan": "", "warnings": []})
    return results



def create_pr(
    branch: str,
    title: str,
    body: str,
    base: str = "main",
    dry_run: bool = False,
) -> dict:
    """Create a GitHub PR via `gh` CLI.

    Assumes the branch already exists remotely (push first).  Returns
    {"created": bool, "dry_run": bool, "pr_url": str|None, ...}.
    """
    if dry_run:
        return {"created": False, "dry_run": True, "branch": branch, "title": title, "base": base}
    # verify gh exists
    try:
        subprocess.run(["gh", "--version"], capture_output=True, check=True)
    except (FileNotFoundError, subprocess.CalledProcessError):
        return {"created": False, "error": "gh CLI not found; install gh or set HERMES_GITHUB_TOKEN"}
    cmd = ["gh", "pr", "create", "--base", base, "--head", branch, "--title", title, "--body", body]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
        if result.returncode == 0:
            url = result.stdout.strip().splitlines()[-1] if result.stdout.strip() else None
            return {"created": True, "dry_run": False, "pr_url": url, "stdout": result.stdout}
        return {"created": False, "error": result.stderr.strip() or result.stdout.strip(), "returncode": result.returncode}
    except Exception as exc:
        return {"created": False, "error": str(exc)}


def git_push_branch(branch: str, dry_run: bool = False) -> dict:
    """Push the current branch to origin.  No-op in dry-run."""
    if dry_run:
        return {"pushed": False, "dry_run": True, "branch": branch}
    try:
        result = subprocess.run(["git", "push", "-u", "origin", branch], capture_output=True, text=True, timeout=30)
        if result.returncode == 0:
            return {"pushed": True, "stdout": result.stdout}
        return {"pushed": False, "error": result.stderr.strip(), "returncode": result.returncode}
    except Exception as exc:
        return {"pushed": False, "error": str(exc)}


# ---------------------------------------------------------------------------
# High-level run helper (used by CLI + tests)
# ---------------------------------------------------------------------------

def run_architect(
    dry_run: bool = False,
    branch: str | None = None,
    title: str | None = None,
    body: str | None = None,
    base: str = "main",
    force: bool = False,
    dsn: str | None = None,
    webhook_payload: dict | None = None,
) -> int:
    """High-level orchestration (dry-run aware, kill-switch gated).

    Returns an exit code (0 = success/skip, 1 = error).
    """
    if not require_enabled(force=force):
        print("architect: HERMES_AGENT_ENABLED != true — kill switch active, exiting (no-op).", file=sys.stderr)
        return 0

    if dry_run:
        print("architect: DRY-RUN — no files, DB writes, pushes, or webhooks will execute.")
        if branch:
            print(f"  would push branch: {branch}")
        if title:
            print(f"  would create PR: {title!r} ({base} <- {branch})")
        if webhook_payload or os.environ.get("HERMES_WEBHOOK_URL"):
            print("  would notify webhook: HERMES_WEBHOOK_URL")
        print("  would log hit to data/hits.jsonl (dry-run: not written)")
        return 0

    # Real run: if branch/title provided, do git push + PR + webhook
    if branch and title:
        push_res = git_push_branch(branch, dry_run=False)
        if not push_res.get("pushed"):
            print(f"architect: git push failed: {push_res.get('error')}", file=sys.stderr)
            return 1
        pr_res = create_pr(branch, title, body or "", base=base, dry_run=False)
        if not pr_res.get("created"):
            print(f"architect: gh pr create failed: {pr_res.get('error')}", file=sys.stderr)
            return 1
        print(f"architect: PR created: {pr_res.get('pr_url')}")
        if webhook_payload is None:
            webhook_payload = {"event": "architect.pr_created", "branch": branch, "title": title, "pr_url": pr_res.get("pr_url")}
        notify_webhook(webhook_payload)
    elif webhook_payload:
        notify_webhook(webhook_payload)
    return 0



def is_agent_enabled(env: dict | None = None) -> bool:
    """Return True iff HERMES_AGENT_ENABLED is truthy.

    Accepts "1", "true", "yes", "on" (case-insensitive).  Default OFF when
    unset or any other value, including "0"/"false"/"no"/"".
    """
    src = env if env is not None else os.environ
    raw = str(src.get("HERMES_AGENT_ENABLED", "")).strip().lower()
    return raw in ("1", "true", "yes", "on", "enabled")


def require_enabled(force: bool = False) -> bool:
    """Gate helper — returns True if agent may proceed; False if blocked.

    If --force is passed the gate is bypassed (useful for local testing).
    Callers should exit early with code 0 when blocked so CI treats the
    skip as success rather than failure.
    """
    if force:
        return True
    return is_agent_enabled()


